## Simulated data sets for Section 5 of the paper (mixed response). Run from
## the repository root:
##   Rscript mixed-response/make_data.R
##
## Both data sets share the design of Section 5.1: n = 500, two covariates
## drawn as (Unif(-3, 1), Unif(-1, 1)) and standardised, and the parameter
## values of equation (simparams),
##   beta = (1, 0.5), mu_d = -1, lam_d = 1, mu_c = 0, lam_c = 1, sigma^2 = 1,
##   xi = (-1, 3), theta = kappa(0.1 (xi_0 + xi_1 W)).
##
## The Gaussian-copula data set is the one analysed in the paper. It is
## recovered from the saved workspace of the original run when that file is
## available (set LVC_GAUSS_RDATA to its path); the copy in data/ is what the
## scripts use, so this step is only needed to regenerate it. The
## Gumbel-copula data set is generated here, with the same covariates.

source("mixed-response/mixed_model.R")
dir.create("mixed-response/data", showWarnings = FALSE)

truth <- list(beta = c(1, 0.5), p = c(mud = -1, lamd = 1, muc = 0, lamc = 1, ssq = 1),
              xi = c(-1, 3), gam = 0.1)

## ---- Gaussian copula: the paper's data set ------------------------------
rdata <- Sys.getenv("LVC_GAUSS_RDATA", "")
if (nzchar(rdata) && file.exists(rdata)) {
  e <- new.env(); load(rdata, envir = e)
  DAT <- e$DAT
  stopifnot(length(DAT$q) == 500, ncol(DAT$X) == 2)
  gauss <- list(q = DAT$q, y = DAT$y, X = unname(DAT$X), W = DAT$w,
                family = "Gaussian", truth = truth,
                note = "data set of Section 5.1 of the paper, recovered from the original run")
  saveRDS(gauss, "mixed-response/data/sim_Gaussian.rds")
  cat("wrote mixed-response/data/sim_Gaussian.rds from", rdata, "\n")
} else if (!file.exists("mixed-response/data/sim_Gaussian.rds")) {
  stop("sim_Gaussian.rds is missing and LVC_GAUSS_RDATA is not set")
}
gauss <- readRDS("mixed-response/data/sim_Gaussian.rds")
cat(sprintf("Gaussian data: n = %d, mean q = %.3f, max q = %d, mean y = %.3f, Kendall tau = %.3f\n",
            length(gauss$q), mean(gauss$q), max(gauss$q), mean(gauss$y),
            cor(gauss$q, gauss$y, method = "kendall")))

## ---- Gumbel copula: same covariates, same parameters ----------------------
set.seed(2026)
X <- gauss$X
W <- as.numeric(X %*% truth$beta) + rnorm(nrow(X))
d <- simulate_mixed(W, truth$p, truth$xi, "Gumbel", truth$gam)
gumbel <- list(q = d$q, y = d$y, X = X, W = W, family = "Gumbel", truth = truth,
               note = "generated by make_data.R, seed 2026")
saveRDS(gumbel, "mixed-response/data/sim_Gumbel.rds")
cat(sprintf("Gumbel data:   n = %d, mean q = %.3f, max q = %d, mean y = %.3f, Kendall tau = %.3f, theta in [%.2f, %.2f]\n",
            length(d$q), mean(d$q), max(d$q), mean(d$y),
            cor(d$q, d$y, method = "kendall"), min(d$theta), max(d$theta)))
